#!/usr/bin/env python3
"""Build vendors.conf from the IEEE OUI registries.

Run on your laptop (not the router) whenever you want to refresh the list:

    curl -O https://standards-oui.ieee.org/oui/oui.csv
    curl -O https://standards-oui.ieee.org/oui28/mam.csv
    curl -O https://standards-oui.ieee.org/oui36/oui36.csv
    python3 build-vendors.py oui.csv mam.csv oui36.csv > ../vendors.conf

To add a manufacturer, add a line to VENDORS: a short key (used in
ranges.conf) and a regex matched against the IEEE "Organization Name".
Run it and check the comments in the output: regexes can catch the wrong
company (e.g. "extron" also matches "Flextronics"), so anchor them.
"""
import csv
import re
import sys

# key -> regex on IEEE organization name (case-insensitive)
VENDORS = {
    "crestron":   r"^crestron electronics",
    "qsc":        r"^qsc (llc|ag)\b",
    "biamp":      r"^biamp\b",
    "shure":      r"^shure inc",
    "audinate":   r"^audinate\b",          # Dante modules inside many brands
    "extron":     r"^extron electronics",
    "sennheiser": r"^sennheiser",
    "yamaha":     r"^yamaha corporation",
    "symetrix":   r"^symetrix",
    "clearone":   r"^clearone",
    "atlona":     r"^atlona",
    "kramer":     r"^kramer electronics",
    "aurora":     r"^aurora multimedia",
    "justaddpower": r"^just add power",
    "wyrestorm":  r"^wyrestorm",
    "avpro":      r"^avpro global",
    "visionary":  r"^visionary solutions",
    "vaddio":     r"^vaddio",
    "poly":       r"^(polycom|poly|plantronics)\b",
    "barco":      r"^barco (nv|projection|control)",
    "christie":   r"^christie digital",
    "epson":      r"^seiko epson",
    "planar":     r"^planar llc",
    "lutron":     r"^lutron electronics",
    "savant":     r"^savant systems",
    "control4":   r"^control4",
    "blackmagic": r"^blackmagic design",
    "aja":        r"^aja video",
    "luxul":      r"^luxul",
}


def main(paths):
    rows = []
    for p in paths:
        with open(p, encoding="utf-8", newline="") as f:
            r = csv.reader(f)
            next(r)  # header
            rows += [(row[0], row[1].upper(), row[2].strip()) for row in r if len(row) >= 3]

    print("# vendor  prefixes...   (generated by tools/build-vendors.py from the IEEE registry)")
    print("# 6 hex digits = MA-L (/24), 7 = MA-M (/28), 9 = MA-S (/36)")
    print("# Hand edits are fine; keep one vendor per line.")
    for key, pat in VENDORS.items():
        rx = re.compile(pat, re.I)
        hits = sorted({(a, org) for reg, a, org in rows if rx.search(org)})
        if not hits:
            print(f"# {key}: no match for /{pat}/", file=sys.stderr)
            continue
        orgs = sorted({org for _, org in hits})
        print(f"\n# {' | '.join(orgs)}")
        print(key, " ".join(a for a, _ in hits))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
